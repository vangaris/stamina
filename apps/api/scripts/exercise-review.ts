// Usage: pnpm --filter @stamina/api exercises:review
// Prints (or, with a path argument, writes) the whole exercise library as a Markdown review
// table for Vang's tag review: one row per exercise, grouped by movement pattern.
import { writeFile } from 'node:fs/promises';
import type { Exercise } from '@stamina/contracts';
import { ExerciseLocation, MovementPattern, SessionSlot } from '@stamina/domain';
import { loadExerciseLibrary } from '../src/exercises/node.ts';

/** Image thumbnails are the full wger image shown small, never a copy. */
const THUMBNAIL_WIDTH = 96;
const NONE = '-';

const header = `# Exercise library review

Generated by \`pnpm --filter @stamina/api exercises:review\` from the data files in
\`apps/api/src/exercises/data/*.json\`. Do not edit this file by hand: fix the data file and run the
script again. Names and instructions come from free-exercise-db (public domain); every tag is
Stamina's own and is drafted by agents, so this review is where a person checks them
(ticket 07, "Tags drafted by agents and reviewed by Vang").

What to review, in this order:

1. **High-load areas (safety).** An exercise that loads an area is never shown to a person who
   excluded it, so an area missing here is a safety hole. List every area the exercise loads
   heavily or puts in a demanding or end-range position, stretches and mobility drills included.
   When unsure, the area belongs in the list. Check the wrist and shoulder of every push or
   plank, the knee and hip of every squat, lunge, jump and kneeling stretch, and the lower back of
   every hinge, carry and rotation.
2. **Tags.** Equipment lists everything needed (a dumbbell bench press needs a bench too).
   Locations are only places the exercise really works (no barbells or machines at home or on a
   beach). Slots fit the session (warm-up and cool-down are short mobility; main strength is the
   compound lifts). RIR is yes only for controlled strength work by reps in reserve, never for
   jumps, throws, stretches, mobility, warm-up drills or carries.
3. **Easier and harder.** Real progressions of the same movement, not weak links.
4. **Images match the movement.** Open each thumbnail link and check the wger page shows the same
   exercise with the same equipment. Images are hotlinked from wger, unmodified, and are shown
   with their author, licence and source link wherever they appear (CC-BY-SA).

Record the outcome of the review in the pull request.
`;

const cell = (text: string) => text.replaceAll('|', '\\|');
const list = (items: readonly string[]) => (items.length === 0 ? NONE : items.join(', '));

const library = await loadExerciseLibrary();
const nameOf = new Map(library.map((e) => [e.id, e.name.en]));
const nameOfLink = (id: string | null) => (id === null ? NONE : (nameOf.get(id) ?? `?${id}`));

function imageCell(exercise: Exercise): string {
  const { image } = exercise;
  if (image === null) return NONE;
  const author = image.authorUrl ? `[${image.author}](${image.authorUrl})` : image.author;
  return (
    `<a href="${image.sourceUrl}"><img src="${image.url}" width="${THUMBNAIL_WIDTH}" ` +
    `alt="${exercise.name.en.replaceAll('"', '&quot;')}"></a><br>` +
    `${author}, [${image.licence}](${image.licenceUrl})`
  );
}

const row = (e: Exercise) =>
  `| ${[
    `\`${e.id}\``,
    e.name.en,
    list(e.slots),
    list(e.equipment.length === 0 ? ['bodyweight'] : e.equipment),
    list(e.locations),
    list(e.highLoadAreas),
    e.rirSuitable ? 'yes' : 'no',
    nameOfLink(e.easierId),
    nameOfLink(e.harderId),
    imageCell(e),
  ]
    .map(cell)
    .join(' | ')} |`;

const count = (keep: (e: Exercise) => boolean) => library.filter(keep).length;

const summary = [
  `${library.length} exercises, ${count((e) => e.image !== null)} with an image.`,
  '',
  `Slots: ${Object.values(SessionSlot)
    .map((slot) => `${slot} ${count((e) => e.slots.includes(slot))}`)
    .join(', ')}.`,
  '',
  `Locations: ${Object.values(ExerciseLocation)
    .map((place) => `${place} ${count((e) => e.locations.includes(place))}`)
    .join(', ')}.`,
  '',
  `Bodyweight only: ${count((e) => e.equipment.length === 0)}.`,
];

const sections = Object.values(MovementPattern).flatMap((pattern) => {
  const group = library.filter((e) => e.movementPattern === pattern);
  if (group.length === 0) return [];
  return [
    `## ${pattern} (${group.length})`,
    '',
    '| Id | Name | Slots | Equipment | Locations | High-load areas | RIR | Easier | Harder | Image |',
    '| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |',
    ...[...group].sort((a, b) => (a.id < b.id ? -1 : 1)).map(row),
    '',
  ];
});

const markdown = [header, ...summary, '', ...sections].join('\n');

const target = process.argv[2];
if (target) {
  await writeFile(target, markdown);
  console.error(`wrote ${target} (${library.length} exercises)`);
} else {
  console.log(markdown);
}
